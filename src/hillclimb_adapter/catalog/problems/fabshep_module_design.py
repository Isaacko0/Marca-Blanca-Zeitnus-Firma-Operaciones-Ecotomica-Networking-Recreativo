"""
FABSHIP Module Design Problem (Program Synthesis)

Synthesizes TypeScript code for FABSHIP modules via OpenEvolve.
Generates complete module implementations for Bloque 4.
"""

from typing import Any, Dict
from hillclimb import Problem
from ..verifiers.fsi_verifier import FSIVerifier  # FSI as ultimate metric


class FABSHIPModuleDesignProblem(Problem):
    """Synthesize FABSHIP module TypeScript code via OpenEvolve."""
    
    # Module templates to generate
    MODULE_TYPES = [
        "greenhouse_bioclimatic",
        "aquaponics",
        "bioreactor_spirulina",
        "bioreactor_mycoprotein",
        "insect_farming",
        "perennial_polyculture",
        "solar_dehydrator",
        "fermentation_chamber",
        "freeze_dryer_low_energy",
        "hermetic_silos",
        "evaporative_cooler",
        "root_cellar_bioclimatic",
        "vacuum_sealer_solar",
        "composter_automated",
        "vermicompost",
        "biogas_digester",
        "greywater_treatment",
        "blackwater_biogas",
        "autonomous_delivery_rover",
        "drone_delivery",
        "community_distribution_hub"
    ]
    
    def __init__(self, target_module: str, community_state: Dict[str, Any]):
        if target_module not in self.MODULE_TYPES:
            raise ValueError(f"Unknown module: {target_module}. Must be one of {self.MODULE_TYPES}")
        
        super().__init__(
            name=f"hscsg_fabshep_{target_module}_design",
            verifier=FSIVerifier(),  # Ultimate metric: FSI
            param_space={
                "module_code": str,  # Full TypeScript module code (generated by OpenEvolve)
                "module_config": {
                    "energy_source": ["solar", "wind", "biogas", "hybrid"],
                    "automation_level": ["semi", "full", "autonomous"],
                    "maintenance_interval_hours": (168, 8760),  # 1 week to 1 year
                    "fabshep_compatible": [True],
                    "nutritional_profile": {
                        "calories_per_kg_input": (0, 5000),
                        "protein_g_per_kg_input": (0, 1000),
                        "micronutrient_density": (0, 100),
                        "essential_amino_acids": (0, 100),
                        "omega3_mg_per_kg_input": (0, 5000),
                        "antioxidant_orac": (0, 100000),
                        "fiber_g_per_kg_input": (0, 500),
                        "water_liters_per_kg_input": (0, 10)
                    }
                }
            }
        )
        self.target_module = target_module
        self.community_state = community_state
    
    def get_initial_candidate(self) -> Dict[str, Any]:
        # Return a minimal stub that OpenEvolve will expand
        return {
            "module_code": f"""
// src/core/lib/fabshepNutricia.ts - {self.target_module} module (AUTO-GENERATED by OpenEvolve)
export interface {self.target_module.title().replace('_', '')}Module {{
  id: string;
  type: '{self.target_module}';
  name: string;
  energySource: 'solar' | 'wind' | 'biogas' | 'hybrid';
  automationLevel: 'semi' | 'full' | 'autonomous';
  nutritionalYield: NutritionalProfile;
  cycleClosure: number;  // 0-1
  entropicEfficiency: number;  // 0-1
}}
""",
            "module_config": {
                "energy_source": "solar",
                "automation_level": "autonomous",
                "maintenance_interval_hours": 8760,
                "fabshep_compatible": True,
                "nutritional_profile": {
                    "calories_per_kg_input": 1000,
                    "protein_g_per_kg_input": 100,
                    "micronutrient_density": 50,
                    "essential_amino_acids": 80,
                    "omega3_mg_per_kg_input": 100,
                    "antioxidant_orac": 5000,
                    "fiber_g_per_kg_input": 50,
                    "water_liters_per_kg_input": 2
                }
            }
        }