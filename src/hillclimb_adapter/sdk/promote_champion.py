"""
Promote Hillclimb Champion to HSCSG Production

CLI: python -m hillclimb_adapter.sdk.promote_champion --run-id <run_id> --problem <name>
"""

import asyncio
import argparse
import json
import sys
import subprocess
from pathlib import Path
from ..bridge import hillclimbBridge


async def promote_champion(run_id: str, problem: str, create_pr: bool = True) -> Dict[str, Any]:
    """Promote champion to HSCSG production."""
    
    # Get champion from experiment report
    report_result = await hillclimbBridge.runCLI(["experiment", "report", run_id])
    if report_result["code"] != 0:
        raise RuntimeError(f"Failed to get experiment report: {report_result['stderr']}")
    
    report = json.loads(report_result["stdout"])
    champion = report.get("champion")
    
    if not champion:
        raise ValueError("No champion found in experiment report")
    
    print(f"Champion found: score={champion['score']:.4f}")
    print(f"Metrics: {champion['metrics']}")
    
    # Generate PR with champion code
    if create_pr:
        pr_result = await _create_pr(champion, problem)
        return {"champion": champion, "pr": pr_result}
    
    return {"champion": champion, "pr": None}


async def _create_pr(champion: Dict, problem: str) -> Dict:
    """Create GitHub PR with champion implementation."""
    
    # Determine target files based on problem
    target_files = _get_target_files(problem, champion)
    
    # Create branch
    branch_name = f"hillclimb/champion-{problem}-{champion['run_id'][:8]}"
    subprocess.run(["git", "checkout", "-b", branch_name], check=True, capture_output=True)
    
    # Write champion code to target files
    for file_path, content in target_files.items():
        Path(file_path).parent.mkdir(parents=True, exist_ok=True)
        Path(file_path).write_text(content)
        print(f"Written: {file_path}")
    
    # Commit
    subprocess.run(["git", "add", "."], check=True, capture_output=True)
    subprocess.run([
        "git", "commit", "-m",
        f"feat(hillclimb): champion from {problem} (score: {champion['score']:.4f})\n\n"
        f"Run ID: {champion['run_id']}\n"
        f"Metrics: {json.dumps(champion['metrics'])}\n\n"
        f"Auto-generated by hillclimb_adapter SDK"
    ], check=True, capture_output=True)
    
    # Push and create PR (requires gh CLI)
    subprocess.run(["git", "push", "origin", branch_name], check=True, capture_output=True)
    
    pr_result = subprocess.run([
        "gh", "pr", "create",
        "--title", f"Hillclimb Champion: {problem}",
        "--body", f"Auto-promoted champion from run `{champion['run_id']}`\n\n"
                  f"**Score:** {champion['score']:.4f}\n"
                  f"**Metrics:**\n```json\n{json.dumps(champion['metrics'], indent=2)}\n```\n\n"
                  f"**Problem:** {problem}\n"
                  f"**Climber:** {champion.get('climber', 'unknown')}\n"
                  f"**Evaluations:** {champion.get('evaluations', 'unknown')}\n\n"
                  f"🤖 Generated by hillclimb_adapter SDK",
        "--label", "hillclimb,auto-promoted"
    ], capture_output=True, text=True)
    
    return {
        "branch": branch_name,
        "pr_url": pr_result.stdout.strip() if pr_result.returncode == 0 else None,
        "success": pr_result.returncode == 0
    }


def _get_target_files(problem: str, champion: Dict) -> Dict[str, str]:
    """Map problem to target files and generate content."""
    
    code = champion.get("code", "")
    params = champion.get("params", {})
    
    mapping = {
        "hscsg_fsi_optimization": {
            "src/core/lib/nutritionalOptimizer.ts": _generate_nutritional_optimizer_ts(params),
            "src/core/lib/fabshepNutricia.ts": _generate_fabshep_config_ts(params)
        },
        "hscsg_xi_auditor_tuning": {
            "src/core/lib/entropicAuditor.ts": _generate_entropic_auditor_ts(params)
        },
        "hscsg_cac_optimization": {
            "src/core/lib/automaton.ts": _generate_automaton_config_ts(params),
            "src/core/lib/fabshepNutricia.ts": _generate_fabshep_config_ts(params)
        },
        "hscsg_governance_policy_search": {
            "src/core/lib/integral.ts": _generate_governance_config_ts(params)
        },
        "zeitnus_kit72h_optimization": {
            "docs/kit72h_protocol.md": _generate_kit72h_protocol_md(params)
        }
    }
    
    return mapping.get(problem, {"champion_output.json": json.dumps(champion, indent=2)})


