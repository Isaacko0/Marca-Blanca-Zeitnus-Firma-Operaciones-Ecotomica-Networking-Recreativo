  /**
   * Inicia revisión por pares (proof-of-stake)
   */
  startPeerReview(logId: string, reviewerIds: string[]): boolean {
    const log = this.network.contributionLogs.get(logId)
    if (!log || log.status !== 'claimed') return false

    log.status = 'under_review'
    log.peerReview = reviewerIds.map(reviewerId => ({
      reviewerId,
      reviewedAt: 0, // will be set on submit
      verdict: 'approve' as const, // placeholder
      comments: '',
      confidence: 0,
      stakedReputation: 10, // default stake
    }))

    this.network.updatedAt = now()
    return true
  }

  /**
   * Envía revisión por pares
   */
  submitPeerReview(logId: string, reviewerId: string, review: Omit<PeerReview, 'reviewerId' | 'reviewedAt'>): boolean {
    const log = this.network.contributionLogs.get(logId)
    if (!log || log.status !== 'under_review') return false

    const existingReview = log.peerReview.find(r => r.reviewerId === reviewerId)
    if (!existingReview) return false

    existingReview.reviewedAt = now()
    existingReview.verdict = review.verdict
    existingReview.comments = review.comments
    existingReview.confidence = review.confidence
    existingReview.stakedReputation = review.stakedReputation

    // Check if all reviews complete
    const allComplete = log.peerReview.every(r => r.reviewedAt > 0)
    if (allComplete) {
      this.finalizeValidation(logId)
    }

    this.network.updatedAt = now()
    return true
  }

  /**
   * Finaliza validación basada en revisiones
   */
  private finalizeValidation(logId: string): void {
    const log = this.network.contributionLogs.get(logId)
    if (!log) return

    const approvals = log.peerReview.filter(r => r.verdict === 'approve')
    const rejections = log.peerReview.filter(r => r.verdict === 'reject')
    const avgConfidence = log.peerReview.reduce((sum, r) => sum + r.confidence, 0) / log.peerReview.length

    // Require majority approval + minimum confidence (configurable via governance equation)
    const minReviews = 2
    const minConfidence = 0.6

    if (approvals.length >= minReviews && avgConfidence >= minConfidence && rejections.length === 0) {
      log.status = 'validated'
      log.validatedAt = now()
      log.validatedBy = 'peer_consensus'

      // Calculate TQ value based on activity
      log.acceptedValueTQ = this.calculateContributionTQ(log)
      log.acceptedValueZNU = log.acceptedValueTQ * this.getPriceParity() // TQ → ZNU

      // Update affiliate balances
      this.updateAffiliateBalances(log.affiliateId, log.acceptedValueTQ, log.acceptedValueZNU)
    } else {
      log.status = 'rejected'
    }

    this.network.updatedAt = now()
  }

  /**
   * Calcula valor TQ de una contribución
   */
  private calculateContributionTQ(log: ContributionLog): number {
    // Base: hours * activity intensity
    const baseIntensity: Record<VFType, number> = {
      LaborFlow: 0.1,
      LoveFlow: 0.05,
      CareFlow: 0.08,
      RepairFlow: 0.15,
      ManufactureFlow: 0.5,
    }

    const intensity = baseIntensity[log.activityType] || 0.1
    let tq = log.hoursClaimed * intensity

    // Bonus for deliverables (evidence of value creation)
    tq += log.deliverables.length * 0.5

    return tq
  }

  private getPriceParity(): number {
    // Would come from valueDual.ts oracle
    return 1 // 1 TQ = 1 ZNU baseline
  }

  private updateAffiliateBalances(affiliateId: string, tq: number, znu: number): void {
    const affiliate = this.network.affiliates.get(affiliateId)
    if (affiliate) {
      affiliate.tqBalance += tq
      affiliate.znuBalance += znu
      affiliate.contributedFlows += 1
    }
  }

  /**
   * Hace inmutable un log validado (cuando entra en algoritmo de redistribución)
   */
  makeLogImmutable(logId: string, benefitRedistributionId: string): boolean {
    const log = this.network.contributionLogs.get(logId)
    if (!log || log.status !== 'validated') return false

    log.immutable = true
    log.benefitRedistributionId = benefitRedistributionId
    this.network.updatedAt = now()
    return true
  }

