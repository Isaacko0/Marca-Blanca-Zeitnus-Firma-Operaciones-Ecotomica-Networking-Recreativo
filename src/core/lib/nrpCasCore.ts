  recordEvent(event: Omit<NRPEvent, 'id' | 'ts' | 'validationStatus' | 'redFlags' | 'dualEventId' | 'resourceImpacts' | 'agentRoles' | 'accountingEntries' | 'isReconciled'>): NRPEvent {
    const timestamp = now()
    const eventId = uid()

    const newEvent: NRPEvent = {
      ...event,
      id: eventId,
      ts: timestamp,
      validationStatus: 'pending',
      redFlags: [],
      dualEventId: undefined,
      resourceImpacts: [],
      agentRoles: [],
      accountingEntries: [],
      isReconciled: false,
    }

    this.network.events.set(eventId, newEvent)
    this.network.vfEvents.set(eventId, reaEventToVF(newEvent))
    this.network.reaEvents.set(eventId, newEvent)
    this.network.updatedAt = now()
    return newEvent
  }

  /**
   * Registra dualidad económica (intercambio entre agentes)
   */
  recordEconomicExchange(
    sourceAgentId: string,
    destinationAgentId: string,
    resourceId: string,
    quantity: number,
    unit: string,
    agreementId?: string
  ): EconomicDuality {
    const resource = this.network.resources.get(resourceId)
    const tqValue = resource ? this.tqValuation.calculateResourceTQ(resource) * quantity : quantity * 0.1

    const duality = createEconomicDuality(sourceAgentId, destinationAgentId, resourceId, quantity, unit, tqValue, agreementId)

    // Validate
    const validation = validateEconomicDuality(duality)
    if (!validation.valid) {
      throw new Error(`Economic duality validation failed: ${validation.errors.join(', ')}`)
    }

    // Record both events
    this.network.events.set(duality.sourceEvent.id, duality.sourceEvent)
    this.network.events.set(duality.destinationEvent.id, duality.destinationEvent)
    this.network.dualityLedger.push(duality)

    // Update agent balances
    this.updateAgentBalancesFromDuality(duality)

    this.network.updatedAt = now()
    return duality
  }

  private updateAgentBalancesFromDuality(duality: EconomicDuality): void {
    const sourceAgent = this.network.affiliates.get(duality.sourceEvent.agentId)
    const destAgent = this.network.affiliates.get(duality.destinationEvent.agentId)

    if (sourceAgent) {
      sourceAgent.tqBalance -= duality.valueTransferred
    }
    if (destAgent) {
      destAgent.tqBalance += duality.valueTransferred
    }
  }

  // ============================================
  // BENEFIT REDISTRIBUTION
  // ============================================

  executeBenefitRedistribution(ventureId: string, periodStart: number, periodEnd: number): BenefitRedistributionRecord | null {
    const venture = this.network.ventures.get(ventureId)
    if (!venture) return null

    // Get validated contribution logs for this venture in period
    const logs = Array.from(this.network.contributionLogs.values()).filter(log =>
      log.ventureId === ventureId &&
      log.status === 'validated' &&
      log.validatedAt! >= periodStart &&
      log.validatedAt! <= periodEnd &&
      !log.immutable
    )

    if (logs.length === 0) return null

    // Calculate total revenue (from venture revenue streams)
    const totalRevenueTQ = venture.revenueStreams.reduce((sum, s) => sum + s.tqOut, 0)
    const totalRevenueZNU = venture.revenueStreams.reduce((sum, s) => sum + s.znuOut, 0)
    const totalRevenueUSDC = venture.revenueStreams.reduce((sum, s) => sum + s.usdcIn, 0)

    // Execute redistribution algorithm (governance equation)
    const equation = this.network.governanceEquations.get(venture.benefitRedistributionAlgorithm)
    if (!equation) return null

    // Simplified: use contribution-based distribution with AUT/CDS weights
    const distributions = this.calculateDistributions(logs, venture, totalRevenueTQ, totalRevenueZNU, totalRevenueUSDC)

    // Make logs immutable
    for (const log of logs) {
      this.makeLogImmutable(log.id, '')
    }

    const record: BenefitRedistributionRecord = {
      id: uid(),
      ventureId,
      periodStart,
      periodEnd,
      executedAt: now(),
      totalRevenueTQ,
      totalRevenueZNU,
      totalRevenueUSDC,
      distributions,
      algorithmVersion: equation.version,
      governanceEquationId: equation.id,
    }

    this.network.benefitRedistributions.set(record.id, record)
    this.network.updatedAt = now()
    return record
  }

  private calculateDistributions(
    logs: ContributionLog[],
    venture: NRPVenture,
    totalTQ: number,
    totalZNU: number,
    totalUSDC: number
  ): BenefitDistribution[] {
    // Get equation parameters (simplified)
    const flowWeight = 0.4
    const autWeight = 0.3
    const cdsWeight = 0.2
    const demurrageThreshold = 300
    const demurrageRate = 0.05

    // Calculate weights per affiliate
    const affiliateWeights = new Map<string, number>()
    let totalWeight = 0

    for (const log of logs) {
      const affiliate = this.network.affiliates.get(log.affiliateId)
      if (!affiliate) continue

      // Get AUT/CDS from state (would be imported)
      const aut = 0.5 // placeholder
      const cds = 0.5 // placeholder

      const weight = log.acceptedValueTQ! * (flowWeight + autWeight * aut + cdsWeight * cds)
      affiliateWeights.set(log.affiliateId, (affiliateWeights.get(log.affiliateId) || 0) + weight)
      totalWeight += weight
    }

    // Distribute
    const distributions: BenefitDistribution[] = []
    for (const [affiliateId, weight] of affiliateWeights.entries()) {
      const affiliate = this.network.affiliates.get(affiliateId)!
      const share = weight / totalWeight

      const amountTQ = totalTQ * share
      const amountZNU = totalZNU * share
      const amountUSDC = totalUSDC * share

      // Demurrage anti-acumulación (Ley II MJ)
      let demurrageApplied = 0
      if (affiliate.znuBalance > demurrageThreshold) {
        demurrageApplied = (affiliate.znuBalance - demurrageThreshold) * demurrageRate
      }

      distributions.push({
        affiliateId,
        amountTQ: +(amountTQ - demurrageApplied).toFixed(2),
        amountZNU: +(amountZNU - demurrageApplied).toFixed(2),
        amountUSDC: +(amountUSDC - demurrageApplied).toFixed(2),
        basis: `flows ${logs.filter(l => l.affiliateId === affiliateId).length} × AUT ${aut.toFixed(2)} × CDS ${cds.toFixed(2)}`,
        tier: affiliate.coreGroupMember ? 'core' : 'contributor',
      })

      // Update balances
      affiliate.tqBalance += amountTQ
      affiliate.znuBalance += amountZNU - demurrageApplied
    }

    return distributions
  }

